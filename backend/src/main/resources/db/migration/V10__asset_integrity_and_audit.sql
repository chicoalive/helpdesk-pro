-- Stop safely if legacy codes collide. Do not rename or merge existing equipment.
DO $$ BEGIN
 IF EXISTS (SELECT 1 FROM assets GROUP BY upper(btrim(code)) HAVING count(*) > 1) THEN
  RAISE EXCEPTION 'Asset codes require an authorized collision review before migration';
 END IF;
END $$;
ALTER TABLE assets ADD COLUMN version bigint NOT NULL DEFAULT 0;
ALTER TABLE assets ADD CONSTRAINT assets_version_nonnegative CHECK (version >= 0);
CREATE UNIQUE INDEX assets_normalized_code_unique ON assets (upper(btrim(code)));
CREATE TABLE asset_audit_logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id bigint NOT NULL REFERENCES assets(id),
 actor_id bigint NOT NULL REFERENCES users(id),
 operation varchar(64) NOT NULL CHECK (operation IN ('ASSET_CREATED','ASSET_UPDATED')),
 occurred_at timestamp with time zone NOT NULL
);
CREATE INDEX asset_audit_asset_time ON asset_audit_logs(asset_id,occurred_at,id);
CREATE TABLE asset_audit_changes (
 audit_id bigint NOT NULL REFERENCES asset_audit_logs(id),
 field_name varchar(255) NOT NULL CHECK (field_name IN ('code','type','description','status')),
 old_value text,
 new_value text,
 PRIMARY KEY(audit_id,field_name)
);
