CREATE UNIQUE INDEX users_email_normalized_key ON public.users (lower(btrim(email)));

CREATE TABLE public.user_audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint NOT NULL REFERENCES public.users(id),
    user_id bigint NOT NULL REFERENCES public.users(id),
    assigned_role varchar(255) NOT NULL CHECK (assigned_role IN ('ADMIN', 'TECHNICIAN', 'REQUESTER')),
    operation varchar(64) NOT NULL,
    occurred_at timestamp(6) with time zone NOT NULL
);

CREATE INDEX user_audit_logs_user_time_idx ON public.user_audit_logs(user_id, occurred_at, id);
