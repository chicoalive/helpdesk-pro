CREATE TABLE public.password_recovery_requests (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES public.users(id),
 requested_at timestamp(6) with time zone NOT NULL,
 status varchar(20) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED','USED','REVOKED','EXPIRED')),
 session_version bigint NOT NULL CHECK(session_version >= 0),
 approved_by_id bigint REFERENCES public.users(id),
 decided_at timestamp(6) with time zone,
 token_hash varchar(64) UNIQUE,
 expires_at timestamp(6) with time zone,
 version bigint NOT NULL DEFAULT 0,
 CHECK ((status = 'APPROVED' AND token_hash IS NOT NULL AND expires_at IS NOT NULL) OR status <> 'APPROVED')
);
CREATE UNIQUE INDEX password_recovery_one_live_idx ON public.password_recovery_requests(user_id)
 WHERE status IN ('PENDING','APPROVED');
CREATE INDEX password_recovery_status_time_idx ON public.password_recovery_requests(status,requested_at,id);
CREATE TABLE public.password_recovery_rate (
 bucket_key varchar(64) PRIMARY KEY,
 window_started timestamp(6) with time zone NOT NULL,
 attempts integer NOT NULL CHECK(attempts >= 0)
);
CREATE TABLE public.password_recovery_guard (id integer PRIMARY KEY CHECK(id=1));
