-- Local maintenance is separate from an authenticated application actor.
CREATE TABLE maintenance_installation (
 id integer PRIMARY KEY CHECK(id=1), installation_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid()
);
INSERT INTO maintenance_installation(id) VALUES(1);
CREATE TABLE maintenance_audit_logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 request_id uuid NOT NULL UNIQUE,
 operator_sid varchar(184) NOT NULL,
 operator_name varchar(255) NOT NULL,
 target_user_id bigint REFERENCES users(id),
 reason varchar(255) NOT NULL,
 result varchar(32) NOT NULL CHECK(result IN ('SUCCESS','FAILED')),
 result_code varchar(64) NOT NULL,
 backup_sha256 varchar(64) NOT NULL,
 occurred_at timestamp with time zone NOT NULL
);
CREATE INDEX maintenance_audit_target_time ON maintenance_audit_logs(target_user_id,occurred_at,id);
